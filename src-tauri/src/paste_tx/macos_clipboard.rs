//! Native pasteboard primitives, shared by production and the main-thread
//! integration test. No Tauri runtime or application settings required.
use objc2::rc::Retained;
use objc2::runtime::ProtocolObject;
use objc2::{define_class, msg_send, AnyThread, DefinedClass};
use objc2_app_kit::{NSPasteboard, NSPasteboardItem, NSPasteboardTypeString, NSPasteboardWriting};
use objc2_foundation::{NSArray, NSData, NSInteger, NSObject, NSString};

/// Concealment marker types declared alongside the text so that well-behaved
/// third-party clipboard managers (Maccy, Paste, ...) skip the transcript.
/// Fewer eager readers means a receipt is more likely to be the actual target.
/// These are conventions; nothing enforces them.
pub(crate) const CONCEALMENT_TYPES: [&str; 3] = [
    "org.nspasteboard.TransientType",
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType",
];

pub struct ProviderIvars {
    delivered: Box<dyn Fn() + Send + Sync>,
    ownership_lost: Box<dyn Fn() + Send + Sync>,
    text: String,
}

define_class!(
    // SAFETY: NSObject has no subclassing requirements and the ivars are
    // plain Rust values guarded by a Mutex.
    #[unsafe(super(NSObject))]
    #[name = "HandyPasteProvider"]
    #[ivars = ProviderIvars]
    pub struct HandyPasteProvider;

    impl HandyPasteProvider {
        // NSPasteboardOwner informal protocol: the pasteboard is asking for the
        // promised data — our receipt that a consumer read the clipboard.
        #[unsafe(method(pasteboard:provideDataForType:))]
        fn pasteboard_provide_data_for_type(&self, pasteboard: &NSPasteboard, data_type: &NSString) {
            let ivars = self.ivars();
            // SAFETY: NSPasteboardTypeString is a read-only framework static.
            let is_text = unsafe { data_type.isEqualToString(NSPasteboardTypeString) };
            // Only a text read counts as a receipt: a request for one of the
            // concealment marker types is a clipboard manager inspecting the
            // markers, not the paste target reading the transcript.
            let payload = if is_text {
                NSString::from_str(&ivars.text)
            } else {
                // Concealment marker types are never handed out.
                NSString::from_str("")
            };
            // Record successful provision, not merely a request. A failed
            // write is not delivery evidence and must time out unconfirmed.
            if pasteboard.setString_forType(&payload, data_type) && is_text {
                (ivars.delivered)();
            }
        }

        #[unsafe(method(pasteboardChangedOwner:))]
        fn pasteboard_changed_owner(&self, _pasteboard: &NSPasteboard) {
            (self.ivars().ownership_lost)();
        }
    }
);

impl HandyPasteProvider {
    pub(crate) fn new(
        text: String,
        delivered: Box<dyn Fn() + Send + Sync>,
        ownership_lost: Box<dyn Fn() + Send + Sync>,
    ) -> Retained<Self> {
        let this = Self::alloc().set_ivars(ProviderIvars {
            delivered,
            ownership_lost,
            text,
        });
        unsafe { msg_send![super(this), init] }
    }
}

/// Materialized bytes for every advertised format and every pasteboard item.
/// Refuse publication if a format cannot be read: preserving the original
/// clipboard is more important than silently degrading it to plain text.
#[derive(Debug, PartialEq)]
pub(crate) struct ClipboardSnapshot(pub(crate) Vec<Vec<(String, Vec<u8>)>>);

#[derive(Debug)]
pub(crate) struct RestoreFailure {
    pub message: String,
    /// If publication failed after clearing and no further writer intervened,
    /// explicit recovery may retry against this exact empty-board generation.
    pub cleared_count: Option<NSInteger>,
}

impl ClipboardSnapshot {
    pub(crate) fn capture(board: &NSPasteboard) -> Result<Self, String> {
        let before = board.changeCount();
        let mut items = Vec::new();
        if let Some(originals) = board.pasteboardItems() {
            for original in originals.iter() {
                let mut formats = Vec::new();
                for kind in original.types().iter() {
                    let data = original.dataForType(&kind).ok_or_else(|| {
                        "Cannot safely preserve an unavailable clipboard format".to_string()
                    })?;
                    formats.push((kind.to_string(), data.to_vec()));
                }
                items.push(formats);
            }
        }
        if board.changeCount() != before {
            return Err("Clipboard changed while saving its contents; paste cancelled".into());
        }
        Ok(Self(items))
    }

    #[allow(dead_code)] // Used by the standalone main-thread integration test.
    pub(crate) fn restore(&self, board: &NSPasteboard) -> Result<(), String> {
        self.restore_inner(board, None)
            .map(|_| ())
            .map_err(|error| error.message)
    }

    /// Recheck ownership after preparing all formats and immediately before
    /// mutation. NSPasteboard has no atomic compare-and-swap operation.
    pub(crate) fn restore_if_owned(
        &self,
        board: &NSPasteboard,
        count: NSInteger,
    ) -> Result<bool, RestoreFailure> {
        self.restore_inner(board, Some(count))
    }

    fn restore_inner(
        &self,
        board: &NSPasteboard,
        expected: Option<NSInteger>,
    ) -> Result<bool, RestoreFailure> {
        let mut items = Vec::new();
        for formats in &self.0 {
            let item = NSPasteboardItem::new();
            for (kind, bytes) in formats {
                if !item.setData_forType(&NSData::with_bytes(bytes), &NSString::from_str(kind)) {
                    return Err(RestoreFailure {
                        message: "Could not prepare a saved clipboard format".into(),
                        cleared_count: None,
                    });
                }
            }
            // Restoration is generated by Handy, not a new user copy. Keep
            // Maccy from recording a second history entry for this operation.
            if !item.setData_forType(
                &NSData::with_bytes(&[]),
                &NSString::from_str(CONCEALMENT_TYPES[0]),
            ) {
                return Err(RestoreFailure {
                    message: "Could not mark clipboard restoration as temporary".into(),
                    cleared_count: None,
                });
            }
            items.push(ProtocolObject::<dyn NSPasteboardWriting>::from_retained(
                item,
            ));
        }
        let objects = NSArray::from_retained_slice(&items);
        if expected.is_some_and(|count| board.changeCount() != count) {
            return Ok(false);
        }
        let cleared = board.clearContents();
        if !items.is_empty() && !board.writeObjects(&objects) {
            return Err(RestoreFailure {
                message: "Could not restore saved clipboard contents".into(),
                cleared_count: (board.changeCount() == cleared).then_some(cleared),
            });
        }
        Ok(true)
    }
}

pub(crate) fn publish(
    board: &NSPasteboard,
    provider: &HandyPasteProvider,
) -> Result<NSInteger, String> {
    let mut types = vec![NSString::from_str("public.utf8-plain-text")];
    types.extend(CONCEALMENT_TYPES.map(NSString::from_str));
    let types = NSArray::from_retained_slice(&types);
    let count: NSInteger = unsafe { msg_send![board, declareTypes: &*types, owner: provider] };
    if count <= 0 {
        return Err("Could not publish the temporary clipboard item".into());
    }
    Ok(count)
}
